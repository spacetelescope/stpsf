#!/usr/bin/env python
"""Generate the HST / WFC3 data files used by stpsf.hst from a TinyTim source distribution.

Writes, under ``$STPSF_PATH`` (or ``--outdir``):

    HST/HST_primary_mirror_map.fits      OPD in metres (primary.new x 547 nm)
    HST/HST_secondary_mirror_map.fits    OPD in metres (second.new  x 547 nm)
    WFC3/filters.tsv                     filter name and number of wavelengths for synphot binning
    WFC3/filters/<FILT>_throughput.fits  throughput curves from wfc3ir.fil / wfc3uvis.fil (nm -> Angstrom)
    WFC3/WFC3_tinytim_model.fits         per-detector model parameters from wfc3_{ir,uvis1,uvis2}.{pup,tab}

Usage::

    python make_hst_data.py --tinytim /path/to/tinytim [--outdir /path/to/stpsf-data]

The conversion is lossless with respect to the TinyTim files; no physical conventions are changed here.
All coefficient arrays are stored exactly as in the ``.pup`` files, with the unit conversion recorded in headers.
"""
import argparse
import datetime
import os
import re

import astropy.io.fits as fits
import numpy as np

MAP_SHAPE = (344, 344)
TT_REF_WAVELENGTH_M = 547e-9
DETECTORS = {
    # name: (pup/tab basename, channel, field-polynomial scale d [pix], unit conversion divisor, y offset [pix])
    'IR': ('wfc3_ir', 'IR', 10.24, 0.547, 0),
    'UVIS1': ('wfc3_uvis1', 'UVIS', 40.96, 0.547 / 0.6328, 2048),
    'UVIS2': ('wfc3_uvis2', 'UVIS', 40.96, 0.547 / 0.6328, 0),
}
# Number of wavelengths for synphot binning, by filter type (name suffix)
NLAMBDA_BY_TYPE = {'W': 21, 'X': 21, 'LP': 21, 'M': 9, 'N': 5, 'Q': 5}


class TokenReader:
    """Sequentially read numeric tokens from a TinyTim ``.pup``/``.tab`` file (comments after # or = removed)."""

    def __init__(self, path):
        self.tokens = []
        with open(path) as f:
            for line in f:
                line = line.split('#')[0].split('=')[0]
                self.tokens.extend(line.split())
        self.pos = 0

    def take(self, n=1):
        vals = [float(t) for t in self.tokens[self.pos : self.pos + n]]
        if len(vals) != n:
            raise ValueError('Ran out of tokens')
        self.pos += n
        return vals[0] if n == 1 else np.array(vals)

    def remaining(self):
        return len(self.tokens) - self.pos


def read_mirror_map(path):
    data = np.fromfile(path, dtype='<f4')
    if data.size != MAP_SHAPE[0] * MAP_SHAPE[1]:
        raise ValueError(f'Unexpected size for {path}: {data.size}')
    return data.reshape(MAP_SHAPE)


def write_mirror_maps(tinytim, outdir):
    os.makedirs(os.path.join(outdir, 'HST'), exist_ok=True)
    for src, name, desc in [('primary.new', 'primary', 'HST primary'), ('second.new', 'secondary', 'HST secondary')]:
        waves = read_mirror_map(os.path.join(tinytim, src))
        hdu = fits.PrimaryHDU((waves.astype(np.float64) * TT_REF_WAVELENGTH_M).astype(np.float32))
        h = hdu.header
        h['BUNIT'] = ('meter', 'OPD units')
        h['TELESCOP'] = 'HST'
        h['DESCRIP'] = f'{desc} mirror zonal OPD map from TinyTim {src}'
        h['SOURCE'] = (src, 'TinyTim file (waves at 547 nm, float32 LE)')
        h['REFWAVE'] = (547e-9, 'Reference wavelength of the original map [m]')
        if name == 'primary':
            h['PUPRADPX'] = (135.15, 'Pupil radius in map pixels (TinyTim map.c)')
        h['HISTORY'] = f'Generated by dev_utils/make_hst_data.py on {datetime.date.today().isoformat()}'
        hdu.writeto(os.path.join(outdir, 'HST', f'HST_{name}_mirror_map.fits'), overwrite=True)


def parse_fil(path):
    """Return {filter: (wavelength_nm, throughput)} from a TinyTim .fil file."""
    out = {}
    with open(path) as f:
        lines = [ln.split() for ln in f if ln.strip()]
    i = 0
    while i < len(lines):
        name, n = lines[i][0], int(lines[i][1])
        arr = np.array([[float(x) for x in ln[:2]] for ln in lines[i + 1 : i + 1 + n]])
        if arr.shape != (n, 2):
            raise ValueError(f'Bad .fil block for {name}')
        out[name] = (arr[:, 0], arr[:, 1])
        i += 1 + n
    return out


def nlambda_for(filtname):
    for suffix in ('LP', 'W', 'X', 'M', 'N'):
        if filtname.endswith(suffix):
            return NLAMBDA_BY_TYPE[suffix]
    return NLAMBDA_BY_TYPE['Q'] if filtname.startswith('FQ') else 9


def write_filters(tinytim, outdir):
    wdir = os.path.join(outdir, 'WFC3')
    os.makedirs(os.path.join(wdir, 'filters'), exist_ok=True)
    rows = []
    for fil, channel in [('wfc3ir.fil', 'IR'), ('wfc3uvis.fil', 'UVIS')]:
        for name, (wl_nm, thru) in parse_fil(os.path.join(tinytim, fil)).items():
            tbl = fits.BinTableHDU.from_columns(
                [
                    fits.Column(name='WAVELENGTH', format='D', unit='Angstrom', array=wl_nm * 10.0),
                    fits.Column(name='THROUGHPUT', format='D', array=thru),
                ]
            )
            h = tbl.header
            h['WAVEUNIT'] = ('angstrom', 'Wavelength unit')
            h['TELESCOP'] = 'HST'
            h['INSTRUME'] = 'WFC3'
            h['CHANNEL'] = channel
            h['FILTER'] = (name, 'Bandpass filter identifier')
            h['SOURCE'] = (fil, 'TinyTim filter table, peak-normalized')
            tbl.writeto(os.path.join(wdir, 'filters', f'{name}_throughput.fits'), overwrite=True)
            rows.append((name, nlambda_for(name)))
    with open(os.path.join(wdir, 'filters.tsv'), 'w') as f:
        f.write('filter\tnlambda\n')
        for name, n in rows:
            f.write(f'{name}\t{n}\n')
    return rows


def parse_detector(tinytim, det):
    """Parse a TinyTim WFC3 detector's .pup and .tab into a dict of arrays/scalars."""
    base, channel, d, convert, yoff = DETECTORS[det]
    t = TokenReader(os.path.join(tinytim, base + '.pup'))
    p = {'channel': channel, 'scale_d': d, 'convert': convert, 'y_offset': yoff}
    p['ota_secondary_radius'] = t.take()
    p['ota_spider_width'] = t.take()
    p['ota_pads'] = t.take(9).reshape(3, 3)  # (V3, V2, radius)
    p['wave_range_nm'] = t.take(2)
    if channel == 'IR':
        p['cold_mask_secondary_radius'] = t.take()
        p['cold_mask_spider_width'] = t.take()
        p['cold_mask_outer_radius'] = t.take()
        p['cold_mask_xy'] = t.take(2)
        p['rotation_deg'] = t.take()
        p['pixel_size_arcsec'] = t.take()
        p['axial_offset_v2v3'] = t.take(2)
    else:
        p['rotation_deg'] = t.take()
        p['pixel_size_arcsec'] = t.take()
    p['field_aber'] = t.take(5 * 36).reshape(5, 6, 6)
    p['ref_v2v3'] = t.take(2)
    p['ref_xy'] = t.take(2)
    p['center_v2v3'] = t.take(2)
    t.take(4 * 14)  # TinyTim's own distortion polynomials: not used (pysiaf is used instead)
    nk = 3
    kern_waves, kernels = [], []
    for _ in range(nk):
        kern_waves.append(t.take())
        kernels.append(t.take(9).reshape(3, 3))
    p['kernel_waves_um'] = np.array(kern_waves)
    p['kernels'] = np.array(kernels)
    nf = int(t.take())
    fw, fc = [], []
    for _ in range(nf):
        fw.append(t.take())
        fc.append(t.take(36).reshape(6, 6))
    p['kfield_waves_um'] = np.array(fw)
    p['kfield_coeffs'] = np.array(fc)
    if t.remaining() != 0:
        raise ValueError(f'{base}.pup: {t.remaining()} unparsed tokens')

    tab = TokenReader(os.path.join(tinytim, base + '.tab'))
    p['zernike_ref_wave_nm'] = tab.take()
    nz = int(tab.take())
    p['static_zernikes'] = tab.take(nz)
    return p


def write_model(tinytim, outdir):
    hdus = [fits.PrimaryHDU()]
    ph = hdus[0].header
    ph['TELESCOP'] = 'HST'
    ph['INSTRUME'] = 'WFC3'
    ph['DESCRIP'] = 'TinyTim WFC3 model parameters (from wfc3_*.pup and wfc3_*.tab)'
    ph['HISTORY'] = f'Generated by dev_utils/make_hst_data.py on {datetime.date.today().isoformat()}'
    for det in DETECTORS:
        p = parse_detector(tinytim, det)
        h = fits.ImageHDU(p['field_aber'], name=f'{det}_FIELD')
        hh = h.header
        hh['DETECTOR'] = det
        hh['CHANNEL'] = p['channel']
        hh['COMMENT'] = 'Field polynomial for Z4-Z8; array axes (znum, x power, y power)'
        hh['COMMENT'] = 'Units: microns (IR) or waves at 632.8 nm (UVIS); see CONVERT'
        hh['SCALE_D'] = (p['scale_d'], 'x=xdet/SCALE_D, y=(ydet+Y_OFFSET)/SCALE_D')
        hh['Y_OFFSET'] = (p['y_offset'], 'Pixels added to 0-based ydet before scaling')
        hh['CONVERT'] = (p['convert'], 'Divide polynomial value by this to get waves at 547 nm')
        hh['ZREFWAVE'] = (p['zernike_ref_wave_nm'], 'Reference wavelength of Zernike table [nm]')
        hh['ROT_DEG'] = (p['rotation_deg'], 'TinyTim camera rotation, clockwise [deg]')
        hh['PIXSCALE'] = (p['pixel_size_arcsec'], 'TinyTim nominal pixel size [arcsec]')
        hh['WAVEMIN'] = (p['wave_range_nm'][0], 'Minimum detector wavelength [nm]')
        hh['WAVEMAX'] = (p['wave_range_nm'][1], 'Maximum detector wavelength [nm]')
        hh['REF_X'] = (p['ref_xy'][0], 'TinyTim reference detector X (0-based)')
        hh['REF_Y'] = (p['ref_xy'][1], 'TinyTim reference detector Y (0-based)')
        hh['REF_V2'] = (p['ref_v2v3'][0], 'TT pupil-frame V2 of ref pos [arcsec]')
        hh['REF_V3'] = (p['ref_v2v3'][1], 'TT pupil-frame V3 of ref pos [arcsec]')
        hh['CEN_V2'] = (p['center_v2v3'][0], 'TT pupil-frame V2 of camera center [arcsec]')
        hh['CEN_V3'] = (p['center_v2v3'][1], 'TT pupil-frame V3 of camera center [arcsec]')
        hh['OTA_EPS'] = (p['ota_secondary_radius'], 'OTA central obscuration radius / R')
        hh['SPIDER_W'] = (p['ota_spider_width'], 'OTA spider full width / R')
        if p['channel'] == 'IR':
            hh['CM_EPS'] = (p['cold_mask_secondary_radius'], 'Cold mask central obscuration radius / R')
            hh['CM_SPID'] = (p['cold_mask_spider_width'], 'Cold mask spider full width / R')
            hh['CM_ROUT'] = (p['cold_mask_outer_radius'], 'Cold mask outer radius / R')
            hh['CM_X'] = (p['cold_mask_xy'][0], 'Cold mask X offset')
            hh['CM_Y'] = (p['cold_mask_xy'][1], 'Cold mask Y offset')
        hdus.append(h)

        hdus.append(fits.ImageHDU(p['ota_pads'], name=f'{det}_PADS'))
        hdus[-1].header['COMMENT'] = 'Rows: pad (V3, V2, radius/R)'
        hz = fits.ImageHDU(p['static_zernikes'], name=f'{det}_ZSTATIC')
        hz.header['COMMENT'] = 'Static Zernikes Z1..Zn, RMS waves at 547 nm (annular); index 0 = Z1'
        hdus.append(hz)
        hk = fits.ImageHDU(p['kernels'], name=f'{det}_KERNEL')
        hk.header['COMMENT'] = 'Charge diffusion (UVIS) or IPC (IR) 3x3 kernels at wavelengths in WAVE#'
        for i, w in enumerate(p['kernel_waves_um'], 1):
            hk.header[f'WAVE{i}'] = (w, 'microns')
        hdus.append(hk)
        hf = fits.ImageHDU(p['kfield_coeffs'], name=f'{det}_KFIELD')
        hf.header['COMMENT'] = 'Field-dependent kernel coefficients at wavelengths in WAVE# (6x6 polynomials)'
        for i, w in enumerate(p['kfield_waves_um'], 1):
            hf.header[f'WAVE{i}'] = (w, 'microns')
        hdus.append(hf)
    os.makedirs(os.path.join(outdir, 'WFC3'), exist_ok=True)
    fits.HDUList(hdus).writeto(os.path.join(outdir, 'WFC3', 'WFC3_tinytim_model.fits'), overwrite=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--tinytim', required=True, help='Directory containing the TinyTim source files')
    ap.add_argument('--outdir', default=os.environ.get('STPSF_PATH'), help='Output directory (default $STPSF_PATH)')
    args = ap.parse_args()
    if not args.outdir:
        ap.error('Set --outdir or $STPSF_PATH')
    write_mirror_maps(args.tinytim, args.outdir)
    rows = write_filters(args.tinytim, args.outdir)
    write_model(args.tinytim, args.outdir)
    print(f'Wrote HST data under {args.outdir} ({len(rows)} filters)')


if __name__ == '__main__':
    main()
